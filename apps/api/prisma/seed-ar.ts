export async function seedArContent(prisma: PrismaClient): Promise<void> {
  let created = 0;
  let updated = 0;
  let skipped = 0;

  ensureStorageDir();

  for (const def of AR_SEED) {
    const chapter = await prisma.chapter.findFirst({
      where: { name: def.chapterName, grade: def.grade, subject: { name: def.subject } },
      include: { subject: { select: { id: true, boardId: true } } },
    });
    if (!chapter) {
      skipped += 1;
      console.log(`  AR seed skipped "${def.title}": chapter "${def.chapterName}" (grade ${def.grade} ${def.subject}) not found`);
      continue;
    }
    const concept = await prisma.concept.findFirst({
      where: { name: def.conceptName, topic: { chapterId: chapter.id } },
      select: { id: true },
    });
    if (!concept) {
      skipped += 1;
      console.log(`  AR seed skipped "${def.title}": concept "${def.conceptName}" not in "${def.chapterName}"`);
      continue;
    }

    const validation = validateDemoModel(def.modelFile);
    const modelReady = Boolean(validation && validation.status === 'VALID');
    const publishable = modelReady || (Boolean(def.modelFile) && validation?.status === 'WARNINGS');
    if (def.modelFile && !validation) {
      console.log(`  AR seed warning: "${def.title}" demo model missing from ar-demo/ - kept as DRAFT`);
    }

    const modelKey = def.modelFile ? copyModelToStorage(def.modelFile) : null;

    const data = {
      title: def.title,
      description: def.description,
      learningObjective: def.learningObjective,
      instructions: def.instructions,
      difficulty: def.difficulty,
      visibility: 'PUBLIC' as const,
      modelFormat: validation ? ('GLB' as const) : null,
      modelKey,
      modelUrl: modelKey ? `/api/v1/files/${modelKey}` : null,
      thumbnailUrl: null,
      hotspots: def.hotspots ?? undefined,
      validationStatus: validation ? validation.status : ('PENDING' as const),
      validationReport: validation
        ? { checks: validation.checks, warnings: validation.warnings, errors: validation.errors }
        : undefined,
      polygonCount: validation?.polygonCount ?? null,
      fileSizeBytes: validation?.fileSizeBytes ?? null,
      source: def.source,
      license: def.license,
      attribution: def.attribution,
      institutionId: null,
      boardId: chapter.subject?.boardId ?? null,
      subjectId: chapter.subject?.id ?? null,
      chapterId: chapter.id,
      conceptId: concept.id,
      grade: chapter.grade,
      status: def.draft || !publishable ? ('DRAFT' as const) : ('PUBLISHED' as const),
      publishedAt: def.draft || !publishable ? null : new Date(),
    };

    const existing = await prisma.arContent.findFirst({
      where: { title: def.title, institutionId: null },
      select: { id: true },
    });
    if (existing) {
      await prisma.arContent.update({ where: { id: existing.id }, data });
      updated += 1;
    } else {
      await prisma.arContent.create({ data });
      created += 1;
    }
  }

  console.log(`AR content seed: ${created} created, ${updated} updated, ${skipped} skipped (missing curriculum).`);
}
