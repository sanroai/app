// Turns authored question fragments into the checked-in additions map.
//
//   node scripts/qa/build-question-additions.mjs --dir artifacts/qa/questions
//
// The seed is the only path that ever created questions, and a deployment is never
// re-seeded - so a new question had no way to reach production. This map is that
// path: `QuestionService.syncQuestionAdditions` (and `POST /questions/sync-additions`)
// inserts the entries a database is missing, keyed by the question text.
//
// The map is generated rather than hand-written so the escaping cannot drift, and
// every entry is checked here before it is written: the answer must be one of the
// options, exactly one option is correct, and the text must be new.
import fs from 'node:fs';
import path from 'node:path';

const argv = process.argv.slice(2);
const arg = (name, def) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : def;
};

const MAP = 'apps/api/src/content/question-additions.ts';
const dir = arg('--dir', path.join('artifacts', 'qa', 'questions'));

const quote = (value) =>
  `'${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')}'`;

const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^questions-.*\.json$/.test(f)) : [];
if (files.length === 0) {
  console.log(`  no question files in ${dir}`);
  process.exit(0);
}

const problems = [];
const seen = new Set();
const entries = [];

for (const file of files) {
  const payload = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8').replace(/^\uFEFF/, ''));
  const rows = Array.isArray(payload) ? payload : payload.questions ?? [];
  console.log(`  ${file}: ${rows.length} question(s)`);
  for (const row of rows) {
    const where = `${file}: ${row.chapterCode} | ${row.concept}`;
    const text = String(row.text ?? '').trim();
    const answer = String(row.answer ?? '').trim();
    const options = Array.isArray(row.options) ? row.options : [];
    if (!text) { problems.push(`${where}: no text`); continue; }
    if (!answer) { problems.push(`${where}: no answer`); continue; }
    if (seen.has(text)) { problems.push(`${where}: duplicate question text`); continue; }
    if (options.length < 2) { problems.push(`${where}: fewer than two options`); continue; }
    const correct = options.filter((option) => option.isCorrect);
    if (correct.length !== 1) { problems.push(`${where}: ${correct.length} correct options`); continue; }
    if (correct[0].text !== answer) { problems.push(`${where}: answer is not the correct option's text`); continue; }
    if (!row.chapterCode) { problems.push(`${where}: no chapterCode`); continue; }
    if (!row.concept) { problems.push(`${where}: no concept`); continue; }
    if (!String(row.explanation ?? '').trim()) { problems.push(`${where}: no explanation`); continue; }
    seen.add(text);
    entries.push({
      chapterCode: row.chapterCode,
      concept: row.concept,
      type: row.type ?? 'MCQ',
      difficulty: row.difficulty ?? 'MEDIUM',
      marks: row.marks ?? 1,
      text,
      answer,
      explanation: String(row.explanation).trim(),
      options: options.map((option, index) => ({
        text: String(option.text).trim(),
        isCorrect: Boolean(option.isCorrect),
        order: index,
      })),
    });
  }
}

if (entries.length === 0) {
  console.log('  nothing to write');
  process.exit(problems.length ? 1 : 0);
}

const header = `/**
 * Questions authored to close a gap the bank could not close by itself.
 *
 * Mastery needs three pieces of evidence, and a practice set credits a concept once
 * per question. Twenty-seven concepts held three question rows that were really two
 * questions - two rewrites of the same question - so those concepts could never
 * leave INSUFFICIENT_EVIDENCE however well a student did. Each entry here is the
 * genuinely different question for one of them.
 *
 * Keyed by text: \`QuestionService.syncQuestionAdditions\` skips a question the
 * database already has, so re-running is safe. Applied by the seed on a fresh
 * install and by \`POST /questions/sync-additions\` on a deployment, which is never
 * re-seeded.
 *
 * Generated by \`scripts/qa/build-question-additions.mjs\` from
 * \`artifacts/qa/questions/questions-*.json\`.
 */
export type QuestionAddition = {
  chapterCode: string;
  concept: string;
  type: string;
  difficulty: string;
  marks: number;
  text: string;
  answer: string;
  explanation: string;
  options: { text: string; isCorrect: boolean; order: number }[];
};

export const QUESTION_ADDITIONS: QuestionAddition[] = [
`;

const body = entries
  .map((entry) => {
    const options = entry.options
      .map((option) => `      { text: ${quote(option.text)}, isCorrect: ${option.isCorrect}, order: ${option.order} },`)
      .join('\n');
    return `  {
    chapterCode: ${quote(entry.chapterCode)},
    concept: ${quote(entry.concept)},
    type: ${quote(entry.type)},
    difficulty: ${quote(entry.difficulty)},
    marks: ${entry.marks},
    text: ${quote(entry.text)},
    answer: ${quote(entry.answer)},
    explanation: ${quote(entry.explanation)},
    options: [
${options}
    ],
  },`;
  })
  .join('\n');

fs.writeFileSync(MAP, `${header}${body}\n];\n`);

console.log(`  file     : ${MAP}`);
console.log(`  questions: ${entries.length}`);
console.log(`  problems : ${problems.length}`);
for (const problem of problems.slice(0, 20)) console.log(`    FAIL ${problem}`);
process.exit(problems.length ? 1 : 0);
